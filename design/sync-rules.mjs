// Copies the product's settled UI rules into design/rules/, so the designers (and their Claude
// Design project, which imports this repository) read the same rules the code is built to.
//
// The source of truth stays in the owner's documentation, `(claude)/technical_documentation/ui/`,
// which is not in this repository. Run this after any change there:
//
//   node design/sync-rules.mjs
//
// Never edit design/rules/ by hand — the next run overwrites it.

import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '..', '..', '(claude)', 'technical_documentation', 'ui');
const target = join(here, 'rules');

let files;
try {
  files = readdirSync(source).filter((name) => name.endsWith('.md'));
} catch {
  console.error(`No source at ${source} — this script runs only on the owner's machine.`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const today = new Date().toISOString().slice(0, 10);

for (const name of files) {
  const body = readFileSync(join(source, name), 'utf8');
  const header =
    `<!-- Generated by design/sync-rules.mjs on ${today} from (claude)/technical_documentation/ui/${name}.\n` +
    `     Do not edit here: the next sync overwrites it. Ask for a change in design/QUESTIONS.md.\n` +
    `     Paths like DECISIONS.md, HISTORY.md or (claude)/… point at the owner's internal notes, not at this repo. -->\n\n`;
  writeFileSync(join(target, name), header + body);
}

console.log(`Synced ${files.length} files into ${target}`);
